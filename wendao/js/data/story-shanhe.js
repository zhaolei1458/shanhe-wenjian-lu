/* ----------------------------------------------------------------------
 * 章首演出之桥：把主线九章的开篇卷轴（cN_open）接到山河章回文案上。
 * 延迟到-modules 全部求值之后执行；机制演出（中段插章/章末抉择战）沿用参考框架。
 * ---------------------------------------------------------------------- */
(function () {
  const CN = ['一', '二', '三', '四', '五', '六', '七', '八', '九'];
  function apply() {
    try {
      const chapters = QuestSys.CHAPTERS;
      if (!chapters || !GameData || !GameData.STORIES) return;
      chapters.forEach((def, i) => {
        const paras = String(def.story || '').split('\n').map(s => s.trim()).filter(Boolean);
        GameData.STORIES[`c${i + 1}_open`] = {
          id: `c${i + 1}_open`,
          title: `第${CN[i]}章 · ${def.title}`,
          scenes: paras.map(p => ({ t: 'narr', text: p })),
        };
      });
    } catch (e) { /* 桥接失败则维持参考原文，不致白屏 */ }
  }
  if (typeof setTimeout === 'function') setTimeout(apply, 0); else apply();
})();
