// ---- 此地可为之事（E-2）：初到一地，把玩法入口说给玩家 ----
export function pocketLineFor(node) {
  const tags = node.tags || [];
  if (tags.includes('lingdi')) return '此地气机清正，是修行人认的灵地——打坐吐纳，事半功倍。';
  if (tags.includes('market') || tags.includes('hub')) return '有市集就有活路——采买卖、打短工、打听行情；若这城有山门镖局，递帖投效也是门路。';
  if (tags.includes('docks')) return '码头不问出身——扛包挣现钱、打听船期、跟跑江湖的人搭话，消息比货走得远。';
  if (tags.includes('slum')) return '贫民坊水深，但藏龙卧虎——行事小心，逢人多让，说不定就撞见真故事。';
  if (tags.includes('temple') || tags.includes('taoist')) return '清净门庭——焚香问道、请人讲经；若机缘到了，拜师的话也说得出口。';
  if (tags.includes('wild')) return '荒野地界——打坐吐纳没人搅扰，也常有奇遇藏在山石草木之间。';
  if (tags.includes('village')) return '村野地方，人情最重——跟老人搭话有故事，想出远门就问村口的路。';
  return '人生地不熟，先四处看看、找人搭句话——路是问出来的。';
}
